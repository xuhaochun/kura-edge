package com.kura.wires.components.asset;

import java.util.ArrayList;
import java.util.List;

import com.kura.wires.model.asset.AssetConstants;
import com.kura.wires.model.definition.Ad;
import com.kura.wires.model.definition.AdOption;
import com.kura.wires.model.definition.Ocd;
import com.kura.wires.model.definition.Scalar;

/**
 * WireAsset 的组件配置定义（OCD），对照上游 {@code BaseAssetOCD} + {@code WireAssetOCD}。
 * <p>
 * 属性顺序与上游一致：{@code asset.desc}、{@code driver.pid}，随后是 6 个 {@code emit.*} 选项。
 * 描述文案也照抄上游（含上游的 "wheter" 拼写错误）——它是快照/界面文案的兼容面。
 * </p>
 */
public final class WireAssetOcd {

    /**
     * BOOLEAN 类型的默认值用真正的 Boolean：本项目没有 OSGi metatype 的字符串→类型强转层，
     * 存成 "false" 字符串会让 WireAssetOptions 里 `instanceof Boolean` 的判定落空
     * （上游是 Tad 默认值 "false" + ConfigurationAdmin 按类型强转，结果等价）。
     */
    private static final Boolean FALSE = Boolean.FALSE;

    private WireAssetOcd() {
        // 常量类
    }

    /**
     * 构建 WireAsset 的 OCD。
     *
     * @return 定义
     */
    public static Ocd create() {
        final List<Ad> ads = new ArrayList<>();

        final Ad assetDesc = new Ad(AssetConstants.ASSET_DESC_PROP, AssetConstants.ASSET_DESC_PROP, Scalar.STRING,
                false, null);
        assetDesc.setDescription("Asset Description");
        ads.add(assetDesc);

        final Ad driverPid = new Ad(AssetConstants.ASSET_DRIVER_PROP, AssetConstants.ASSET_DRIVER_PROP, Scalar.STRING,
                true, null);
        driverPid.setDescription("Driver Name");
        ads.add(driverPid);

        final Ad emitAllChannels = new Ad(WireAssetOptions.EMIT_ALL_CHANNELS_PROP_NAME,
                WireAssetOptions.EMIT_ALL_CHANNELS_PROP_NAME, Scalar.BOOLEAN, true, FALSE);
        emitAllChannels.setDescription("Specifies wheter the values of all READ or READ_WRITE "
                + "channels should be emitted in case of a channel event."
                + " If set to true, the values for all channels will be read and emitted,"
                + " if set to false, only the value for the channel related to the event will be emitted.");
        ads.add(emitAllChannels);

        final Ad timestampMode = new Ad(WireAssetOptions.TIMESTAMP_MODE_PROP_NAME,
                WireAssetOptions.TIMESTAMP_MODE_PROP_NAME, Scalar.STRING, true, TimestampMode.PER_CHANNEL.name());
        timestampMode.setDescription("If set to PER_CHANNEL, the component will emit a driver-generated timestamp"
                + " per channel property. If set to SINGLE_ASSET_GENERATED, the component will emit a single"
                + " timestamp per request, generated by the Asset itself before emitting the envelope."
                + " If set to SINGLE_DRIVER_GENERATED_MAX or SINGLE_DRIVER_GENERATED_MIN, the component will emit a"
                + " single driver generated timestamp being respectively the max (most recent) or min (oldest)"
                + " among the timestamps of the channels.");
        timestampMode.setOptions(timestampOptions());
        ads.add(timestampMode);

        final Ad emitErrors = new Ad(WireAssetOptions.EMIT_ERRORS_PROP_NAME, WireAssetOptions.EMIT_ERRORS_PROP_NAME,
                Scalar.BOOLEAN, true, FALSE);
        emitErrors.setDescription("Specifies whether channel specific errors should be included or not in emitted"
                + " envelopes. If enabled, the component will add an additional property per channel, named"
                + " \"<channel_name>_error\". If the channel operation fails, the property value will be an error"
                + " message reported by the Driver, if the operation succeeds the property value will be the empty"
                + " string.");
        ads.add(emitErrors);

        final Ad emitConnectionErrors = new Ad(WireAssetOptions.EMIT_CONNECTION_ERRORS_PROP_NAME,
                WireAssetOptions.EMIT_CONNECTION_ERRORS_PROP_NAME, Scalar.BOOLEAN, true, FALSE);
        emitConnectionErrors.setDescription("Specifies whether the component should emit an envelope in case of a"
                + " general connection exception reported by the Driver (for example due to the fact that the"
                + " connection with a remote device cannot be established). The error message associated with the"
                + " exception will be emitted in a property named \"assetError\". In case of connection exception,"
                + " channel values are not available and no channel related properties will be emitted."
                + " If the \"timestamp.mode\" property is set to a value other than \"NO_TIMESTAMPS\", the component"
                + " will also emit a \"assetTimestamp\" property reporting current system time. This property will be"
                + " ignored if \"emit.errors\" is disabled.");
        ads.add(emitConnectionErrors);

        final Ad emitOnChange = new Ad(WireAssetOptions.EMIT_ON_CHANGE_PROP_NAME,
                WireAssetOptions.EMIT_ON_CHANGE_PROP_NAME, Scalar.BOOLEAN, true, FALSE);
        emitOnChange.setDescription("If set to true, this component will include a channel value in the output"
                + " emitted in Kura Wires only if it is different than the one from the previous read operation or"
                + " event. Channel errors will always be emitted if emit.errors is set to true.");
        ads.add(emitOnChange);

        final Ad emitEmptyEnvelopes = new Ad(WireAssetOptions.EMIT_EMPTY_ENVELOPES_PROP_NAME,
                WireAssetOptions.EMIT_EMPTY_ENVELOPES_PROP_NAME, Scalar.BOOLEAN, true, Boolean.TRUE);
        emitEmptyEnvelopes.setDescription("If set to false, this component will not emit empty envelopes."
                + " This property can be useful if combined with emit.on.change.");
        ads.add(emitEmptyEnvelopes);

        return new Ocd(AssetConstants.ASSET_FACTORY_PID, "Wire Asset",
                "Configure Wire Asset Instance", List.copyOf(ads));
    }

    private static List<AdOption> timestampOptions() {
        final List<AdOption> options = new ArrayList<>();
        for (final TimestampMode mode : TimestampMode.values()) {
            options.add(new AdOption(mode.name(), mode.name()));
        }
        return options;
    }
}

-- kura-edge 第二批建表：组件模块（kura-edge-components）自己的 JPA 实体。
-- DbWireRecordStore 落库用，对照上游 org.eclipse.kura.internal.wire.db.store 的建表语义
-- （本项目简化为一条 WireRecord 一行，属性表 JSON 序列化到 prop_value）。

CREATE TABLE wire_records (
    id          BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emitter_pid VARCHAR(255) NOT NULL,
    received_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    prop_value  CLOB         NOT NULL
);
